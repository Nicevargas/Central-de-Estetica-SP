Não existe um número único. Para a qualidade geral da pele, o tratamento costuma ser planejado em um pacote de sessões com intervalo entre elas. Para estrias, a média é de 3 a 6 sessões. Na avaliação, o número de sessões e o intervalo são definidos conforme o seu objetivo e a resposta da sua pele.

